package ru.yojo.codegen.domain;

/**
 * Java type generated for {@code format: date-time} properties.
 * <p>
 * When not configured, {@link #OFFSET_DATE_TIME} is used.
 */
public enum DateTimeType {

    /**
     * {@code java.time.OffsetDateTime} (default).
     */
    OFFSET_DATE_TIME,

    /**
     * {@code java.time.Instant}.
     */
    INSTANT
}
